export const LEVELS = ["A1", "A2", "B1", "B2", "C1", "C2"];

export const VOCAB = Object.fromEntries(
  Object.entries(RAW).map(([level, themes]) => [
    level,
    Object.fromEntries(
      Object.entries(themes).map(([theme, items]) => [
        theme,
        items.map((line) => {
          const [en, pl, emoji, example] = line.split("|");
          return { id: `${level}:${en}`, en, pl, emoji, example, level, theme };
        }),
      ]),
    ),
  ]),
);

export function wordsForLevel(level, { upTo = false } = {}) {
  const levels = upTo ? LEVELS.slice(0, LEVELS.indexOf(level) + 1) : [level];
  return levels.flatMap((l) => Object.values(VOCAB[l] || {}).flat());
}

export function allWords() {
  return LEVELS.flatMap((l) => wordsForLevel(l));
}
